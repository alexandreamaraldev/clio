//! Phase 4 look: per-clip filter (bundled LUT preset + intensity) and colour adjustments.
//!
//! The engine only stores and validates the grade; the app bakes it into one 3D LUT
//! (`ColorGrade` -> cube) used by both the ExoPlayer preview and the Transformer export, so they match.

use crate::{ClioError, ClioProject, State, TrackKind};

/// Colour grade of one video/image clip (main track or overlay layer).
/// Adjustments are -1..1 (0 = neutral). `filter` is a preset id from [`filter_presets`]
/// ("" = none) mixed in at `intensity` (0..1).
#[derive(serde::Serialize, serde::Deserialize, Debug, Clone, PartialEq, uniffi::Record)]
pub struct ColorGrade {
    #[serde(default)]
    pub filter: String,
    #[serde(default = "full")]
    pub intensity: f32,
    #[serde(default)]
    pub brightness: f32,
    #[serde(default)]
    pub contrast: f32,
    #[serde(default)]
    pub saturation: f32,
    /// Negative = cooler (blue), positive = warmer (amber).
    #[serde(default)]
    pub temperature: f32,
    #[serde(default)]
    pub highlights: f32,
    #[serde(default)]
    pub shadows: f32,
}

fn full() -> f32 {
    1.0
}

impl Default for ColorGrade {
    fn default() -> Self {
        ColorGrade { filter: String::new(), intensity: 1.0, brightness: 0.0, contrast: 0.0, saturation: 0.0, temperature: 0.0, highlights: 0.0, shadows: 0.0 }
    }
}

/// A bundled LUT preset. `id` names `assets/luts/<id>.cube` in the app; `label` is pt-BR.
#[derive(Debug, Clone, PartialEq, uniffi::Record)]
pub struct FilterPreset {
    pub id: String,
    pub label: String,
}

/// Preset ids and pt-BR names, in strip order. The LUT files are generated by `tools/gen_luts.py`.
pub const FILTERS: &[(&str, &str)] = &[
    ("quente", "Quente"),
    ("frio", "Frio"),
    ("vivido", "Vívido"),
    ("cinema", "Cinema"),
    ("vintage", "Vintage"),
    ("desbotado", "Desbotado"),
    ("pb", "P&B"),
];

#[uniffi::export]
pub fn filter_presets() -> Vec<FilterPreset> {
    FILTERS.iter().map(|(id, label)| FilterPreset { id: (*id).into(), label: (*label).into() }).collect()
}

impl ColorGrade {
    /// Clamps every field and drops unknown filters, so drafts and the FFI can't store junk.
    pub fn sanitized(&self) -> Self {
        let a = |v: f32| if v.is_finite() { v.clamp(-1.0, 1.0) } else { 0.0 };
        let filter = if FILTERS.iter().any(|(id, _)| *id == self.filter) { self.filter.clone() } else { String::new() };
        ColorGrade {
            intensity: if self.intensity.is_finite() { self.intensity.clamp(0.0, 1.0) } else { 1.0 },
            filter,
            brightness: a(self.brightness),
            contrast: a(self.contrast),
            saturation: a(self.saturation),
            temperature: a(self.temperature),
            highlights: a(self.highlights),
            shadows: a(self.shadows),
        }
    }

    /// True when the grade changes nothing (the app skips the effect).
    pub fn is_neutral(&self) -> bool {
        let g = self.sanitized();
        (g.filter.is_empty() || g.intensity == 0.0)
            && [g.brightness, g.contrast, g.saturation, g.temperature, g.highlights, g.shadows].iter().all(|v| *v == 0.0)
    }
}

/// One clip's grade, as listed in `Snapshot::grades`.
#[derive(Debug, Clone, PartialEq, uniffi::Record)]
pub struct ClipGrade {
    pub clip_id: u64,
    pub grade: ColorGrade,
}

impl State {
    pub(crate) fn grade(&self, clip_id: u64) -> ColorGrade {
        self.grades.get(&clip_id).cloned().unwrap_or_default()
    }
    pub(crate) fn copy_grade(&mut self, from: u64, to: u64) {
        if let Some(g) = self.grades.get(&from).cloned() {
            self.grades.insert(to, g);
        }
    }
    /// Drops grades of deleted clips (undo restores them with the snapshot).
    pub(crate) fn prune_grades(&mut self) {
        let live: std::collections::BTreeSet<u64> = self.tracks.iter().flat_map(|t| t.clips.iter().map(|c| c.id)).collect();
        self.grades.retain(|id, _| live.contains(id));
    }
    pub(crate) fn clip_grades(&self) -> Vec<ClipGrade> {
        self.grades.iter().filter(|(id, g)| self.find(**id).is_some() && !g.is_neutral()).map(|(id, g)| ClipGrade { clip_id: *id, grade: g.clone() }).collect()
    }
    fn set_grade(&mut self, clip_id: u64, g: ColorGrade) {
        if g.is_neutral() { self.grades.remove(&clip_id); } else { self.grades.insert(clip_id, g); }
    }
}

#[uniffi::export]
pub fn grade_is_neutral(grade: ColorGrade) -> bool {
    grade.is_neutral()
}

#[uniffi::export]
impl ClioProject {
    /// Sets the colour grade of a video/image clip (main track or overlay). One undo step; a
    /// no-op change records nothing.
    pub fn set_clip_grade(&self, clip_id: u64, grade: ColorGrade) -> Result<(), ClioError> {
        let mut s = self.st();
        let (ti, _ci) = s.find(clip_id).ok_or_else(|| ClioError::Invalid { msg: format!("no clip {clip_id}") })?;
        if !matches!(s.tracks[ti].kind, TrackKind::Video | TrackKind::Overlay) {
            return Err(ClioError::Invalid { msg: "grade applies to video and layer clips".into() });
        }
        let g = grade.sanitized();
        if s.grade(clip_id) == g {
            return Ok(());
        }
        s.checkpoint();
        s.set_grade(clip_id, g);
        Ok(())
    }

    /// Copies one clip's grade to every main-track clip (one undo step).
    pub fn apply_grade_to_all(&self, clip_id: u64) -> Result<(), ClioError> {
        let mut s = self.st();
        s.find(clip_id).ok_or_else(|| ClioError::Invalid { msg: format!("no clip {clip_id}") })?;
        let g = s.grade(clip_id);
        let ids: Vec<u64> = s.tracks.iter().filter(|t| t.kind == TrackKind::Video).flat_map(|t| t.clips.iter().map(|c| c.id)).collect();
        if ids.iter().all(|id| s.grade(*id) == g) {
            return Ok(());
        }
        s.checkpoint();
        for id in ids {
            s.set_grade(id, g.clone());
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn proj() -> (ClioProject, u64, u64) {
        let p = ClioProject::new("t".into(), 1080, 1920).unwrap();
        let v = p.add_track(TrackKind::Video, "V".into());
        let a = p.append_clip(v, "a".into(), "a.mp4".into(), 2000).unwrap();
        let b = p.append_clip(v, "b".into(), "b.mp4".into(), 3000).unwrap();
        (p, a, b)
    }
    fn grade_of(p: &ClioProject, id: u64) -> ColorGrade {
        p.snapshot().grades.into_iter().find(|g| g.clip_id == id).map(|g| g.grade).unwrap_or_default()
    }
    fn warm() -> ColorGrade {
        ColorGrade { filter: "quente".into(), intensity: 0.6, brightness: 0.2, temperature: 0.3, ..Default::default() }
    }

    #[test]
    fn set_grade_undo_redo() {
        let (p, a, _) = proj();
        assert!(grade_of(&p, a).is_neutral());
        p.set_clip_grade(a, warm()).unwrap();
        assert_eq!(grade_of(&p, a), warm());
        assert!(p.undo());
        assert!(grade_of(&p, a).is_neutral());
        assert!(p.redo());
        assert_eq!(grade_of(&p, a), warm());
    }

    #[test]
    fn unchanged_grade_is_not_an_undo_step() {
        let (p, a, _) = proj();
        p.set_clip_grade(a, warm()).unwrap();
        p.set_clip_grade(a, warm()).unwrap();
        assert!(p.undo());
        assert!(grade_of(&p, a).is_neutral());
    }

    #[test]
    fn grade_is_sanitized() {
        let (p, a, _) = proj();
        let junk = ColorGrade { filter: "nope".into(), intensity: 7.0, brightness: f32::NAN, contrast: -3.0, saturation: 2.0, ..Default::default() };
        p.set_clip_grade(a, junk).unwrap();
        let g = grade_of(&p, a);
        assert_eq!(g.filter, "");
        assert_eq!((g.intensity, g.brightness, g.contrast, g.saturation), (1.0, 0.0, -1.0, 1.0));
    }

    #[test]
    fn grade_only_on_video_and_layers() {
        let (p, _, _) = proj();
        let t = p.add_track(TrackKind::Text, "T".into());
        let txt = p.append_clip(t, "oi".into(), "".into(), 1000).unwrap();
        assert!(p.set_clip_grade(txt, warm()).is_err());
        let o = p.add_overlay("pip".into(), "p.mp4".into(), 0, 1000).unwrap();
        p.set_clip_grade(o, warm()).unwrap();
        assert_eq!(grade_of(&p, o), warm());
    }

    #[test]
    fn split_keeps_grade_on_both_halves() {
        let (p, a, _) = proj();
        p.set_clip_grade(a, warm()).unwrap();
        let r = p.split_clip(a, 1000).unwrap();
        assert_eq!(grade_of(&p, r), warm());
        assert_eq!(grade_of(&p, a), warm());
    }

    #[test]
    fn apply_to_all_is_one_step() {
        let (p, a, b) = proj();
        p.set_clip_grade(a, warm()).unwrap();
        p.apply_grade_to_all(a).unwrap();
        assert_eq!(grade_of(&p, b), warm());
        assert!(p.undo());
        assert!(grade_of(&p, b).is_neutral());
        assert_eq!(grade_of(&p, a), warm());
    }

    #[test]
    fn grade_survives_draft_and_old_drafts_load() {
        let (p, a, _) = proj();
        p.set_clip_grade(a, warm()).unwrap();
        let q = ClioProject::from_draft_json(p.to_draft_json().unwrap()).unwrap();
        assert_eq!(grade_of(&q, a), warm());
        // A pre-phase-4 draft has no `grades` field: it loads neutral.
        let old = p.to_draft_json().unwrap().replace("\"grades\":", "\"_old_grades\":");
        let r = ClioProject::from_draft_json(old).unwrap();
        assert!(grade_of(&r, a).is_neutral());
    }

    #[test]
    fn deleting_a_clip_drops_its_grade_and_undo_restores_it() {
        let (p, a, _) = proj();
        p.set_clip_grade(a, warm()).unwrap();
        assert!(p.remove_clip(a));
        assert!(p.snapshot().grades.is_empty());
        assert!(p.undo());
        assert_eq!(grade_of(&p, a), warm());
    }

    #[test]
    fn presets_have_unique_ids() {
        let ids: std::collections::HashSet<_> = FILTERS.iter().map(|f| f.0).collect();
        assert_eq!(ids.len(), FILTERS.len());
        assert_eq!(filter_presets().len(), FILTERS.len());
    }
}
