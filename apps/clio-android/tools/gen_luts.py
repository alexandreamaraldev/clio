#!/usr/bin/env python3
"""Generates Clio's bundled filter LUTs (assets/luts/<id>.cube, 17^3, Adobe .cube format).

The looks are written from scratch here as simple colour math (no third-party LUTs), so the
generated files are original works released under CC0 1.0 (public domain); see assets/luts/README.md.
Ids must match crates/ffi-mobile/src/look.rs FILTERS (checked by LutAssetsTest).
Run: python3 tools/gen_luts.py
"""
import os

N = 17
OUT = os.path.join(os.path.dirname(__file__), "..", "app", "src", "main", "assets", "luts")


def clamp(v):
    return 0.0 if v < 0 else 1.0 if v > 1 else v


def luma(r, g, b):
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def sat(r, g, b, k):
    l = luma(r, g, b)
    return l + (r - l) * k, l + (g - l) * k, l + (b - l) * k


def contrast(r, g, b, k):
    return tuple((c - 0.5) * k + 0.5 for c in (r, g, b))


def smooth(e0, e1, x):
    t = clamp((x - e0) / (e1 - e0))
    return t * t * (3 - 2 * t)


def quente(r, g, b):
    r, g, b = r * 1.06 + 0.02, g * 1.01 + 0.005, b * 0.88
    return sat(r, g, b, 1.08)


def frio(r, g, b):
    r, g, b = r * 0.9, g * 0.99 + 0.005, b * 1.06 + 0.03
    return sat(r, g, b, 0.97)


def vivido(r, g, b):
    return contrast(*sat(r, g, b, 1.4), 1.1)


def cinema(r, g, b):
    l = luma(r, g, b)
    sh, hi = 1 - smooth(0.0, 0.55, l), smooth(0.45, 1.0, l)
    r += -0.05 * sh + 0.07 * hi
    g += 0.02 * sh + 0.02 * hi
    b += 0.07 * sh - 0.07 * hi
    return contrast(*sat(r, g, b, 0.9), 1.12)


def vintage(r, g, b):
    r, g, b = sat(r, g, b, 0.75)
    r, g, b = r * 0.9 + 0.08, g * 0.88 + 0.06, b * 0.78 + 0.07
    return r * 1.04, g, b * 0.96


def desbotado(r, g, b):
    r, g, b = sat(r, g, b, 0.7)
    return tuple(0.12 + c * 0.8 for c in (r, g, b))


def pb(r, g, b):
    l = luma(r, g, b)
    return contrast(l, l, l, 1.08)


LOOKS = {"quente": quente, "frio": frio, "vivido": vivido, "cinema": cinema,
         "vintage": vintage, "desbotado": desbotado, "pb": pb}


def write(name, f):
    lines = [f'TITLE "Clio {name}"', "# Generated by tools/gen_luts.py. CC0 1.0 (public domain).", f"LUT_3D_SIZE {N}"]
    # .cube order: red changes fastest, then green, then blue.
    for bi in range(N):
        for gi in range(N):
            for ri in range(N):
                rgb = f(ri / (N - 1), gi / (N - 1), bi / (N - 1))
                lines.append(" ".join(f"{clamp(c):.5f}" for c in rgb))
    with open(os.path.join(OUT, f"{name}.cube"), "w") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for k, f in LOOKS.items():
        write(k, f)
